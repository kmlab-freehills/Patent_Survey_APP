def build_idea_prompt(patent_doc, explanation_text):
    prompt = f"""
特許文書に記載された技術について、現実的な活用アイデアを**3件程度**生成してください。

## アイデア生成の指針

### 基本的な問い
すべてのアイデアは、以下の問いに答えるものとしてください：

1. **誰の課題を解決するのか？**（ターゲットの明確化）
2. **どのように解決するのか？**（技術との接続）
3. **なぜこの技術が適しているのか？**（技術的優位性）

### アイデアの多様性
以下のような多様性を持つアイデアを含めてください：

- **近接応用**: 特許文書に記載された用途に近い応用
- **遠隔転用**: 全く異なる分野への転用
- **具体的ニッチ**: 特定の狭い市場・用途に特化したもの

## 重要な原則

### 1. 事実と推測の明確な分離
あなたが生成するアイデアは、以下の2つの要素から構成されます：

**【事実層】特許文書に基づく技術的事実**
- フェーズ1で抽出された情報のみを使用
- 引用または要約の形式で明示

**【推測層】あなたの創造的な解釈・応用**
- 事実層を出発点とした、論理的な推論
- 市場ニーズや応用可能性の想定
- **必ず[推測]とマークする**

### 2. 推測の誠実な表現
推測箇所では、以下のような表現を使用してください：

- 「〜の可能性がある」
- 「〜が期待される」
- 「〜と想定される」
- 「〜への応用が考えられる」

**絶対に使用しないこと：**
- 断定的な表現（「〜である」「〜できる」）
- 根拠なき数値（「約○○%向上」）
- 架空の事例（「A社では〜」）

## 出力テンプレート

各アイデアは、以下の構造で記述してください。
※ （〇〇層）の出力は不要です。--> あなたにとっての参考情報としての位置づけのため。

```markdown
# [特許の名称] アイデアリスト

## アイデア1: [名称]

### 技術的基盤（事実層）

この特許技術は、以下の特性を持つ：
- [特許文書からの引用または要約箇所を出典と共にリストアップ]

### アイデアの概要（推測層）

[上記の技術的基盤を出発点として、どのような応用が考えられるか]

### 解決できる課題（推測層）

[このアイデアがどのような課題を解決するか]

### ターゲット像（推測層）

- 企業: [想定される企業・組織]
- 消費者: [想定される消費者層]

### 提供価値（推測層）

[このアイデアが提供するベネフィット]

### 技術的接続点（事実層 + 推測層）

特許技術の[具体的特性X]により、[期待される効果Y]が見込まれる。[推測]
根拠: （[段落: xxxx]参照）

### 実装上の検討事項（推測層）

- 技術的ハードル: [想定される課題]
- 市場・規制リスク: [想定されるリスク]

## アイデア2: [名称]
...(省略)
```

## 対象技術に関する資料

### 特許技術の構造化
<document>
{explanation_text}
</document>

### 特許原文（前提）
<document>
{patent_doc.get_text()}
</document>

---

上記の指示と資料に基づき、アイデアを生成してください。
""".strip()
    return prompt
