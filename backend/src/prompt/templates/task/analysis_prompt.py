def build_analysis_prompt(patent_text: str) -> str:
    # 資料がない場合のフォールバック（仮）
    if not patent_text:
        pass
    
    prompt = f"""
## 1. 基本原則
- 与えられた資料から、発明や技術に関する**事実のみ**を抽出してください。
- あなた自身の推測・解釈・意見・一般的知識は**一切含めないでください**。
- 資料に明記された表現を優先し、あなたの言葉への言い換えは最小限にとどめてください。

## 2. 該当記述がない場合の対応
各項目について、以下の基準で判断してください：

1. **明確な記述がある** → そのまま抽出
2. **間接的・部分的な記述がある** → 抽出し、「部分的な記述」と明記
3. **該当する記述が見当たらない** → 「該当記述なし」と明記

## 3. 出典の明記
可能な限り、抽出した情報の出典を明示してください：
- 段落番号、図番号、表番号などを併記
  - 例: 文末や行末に[段落: 0023], [図: 2], [請求項: 1] などを記載

## 4. 分類に関する補足

### 複数項目に該当する要素の扱い
同じ要素が複数の項目に該当する場合、**それぞれの側面で記載**してください。

例:
- 項目2-1: 「温度センサー」（物理的構成要素として）
- 項目3-1: 「温度センシング技術」（検出原理として）
- 項目3-2: 「周囲温度の測定」（要素機能として）

### 不明確な分類の場合
どの項目に該当するか判断が難しい場合、**最も適切と思われる項目に記載**し、その旨を注記してください。

## 5. 出力テンプレート

抽出内容は、以下の構造で記述してください。

```markdown
# [特許の名称]

## 1. 発明の技術分野
【技術分野】に記載されている分野を、原文の表現に沿って簡潔に記述してください。

---

## 2. 技術の物理的構成

### 2-1. 構成要素（部材・部品）
**物理的な形状を持つ**部材、部品、機材、機械を箇条書きでリストアップ。
- 該当例: モーター、センサー筐体、フレーム、ギア、配線
- 非該当例: ソフトウェア、アルゴリズム、製造方法

### 2-2. 構成材料・原料
構成要素を**作るための材料・材質**を箇条書きでリストアップ。
- 該当例: 金属、樹脂、化学物質、合金、繊維
- 非該当例: 完成した部品（それは2-1に記載）

### 2-3. 形態・形状・構造
技術が「どのような形・構造」をしているかを記述。
- 全体の形状、配置関係、構造的特徴など

---

## 3. 技術の機能的構成

### 3-1. 基盤技術・要素技術
**技術的な原理、方法論、プロセス**を箇条書きでリストアップ。
- 該当例: 製造方法、制御アルゴリズム、信号処理技術、化学反応原理
- 非該当例: 物理的な部品（それは2-1に記載）

### 3-2. 要素機能（部品レベル）
各構成要素が果たす**個別の役割**を記述。

### 3-3. システム機能（全体レベル）
技術全体として実現される**主要な機能**を記述。

### 3-4. 動作フロー（該当記述がある場合のみ）
技術が**どのような順序で動作するか**、プロセスやシーケンスを記述。

---

## 4. 定量データ・仕様情報

以下のルールで数値データを抽出してください：

**抽出原則:**
1. **原文に忠実に**: 「約」「およそ」「〜以上」などの修飾語も含める
2. **文脈を保持**: 数値が何を示すかを明記
3. **出典を明記**: 段落番号、図番号、表番号を併記
4. **範囲と条件**: 数値に条件がある場合、その条件も記載

**抽出対象:**
- 寸法・サイズ
- 物理量
- 性能指標
- 配合・比率
- その他の定量的記述
```

## 対象資料
<document>
{patent_text.strip()}
</document>
""".strip()

    return prompt